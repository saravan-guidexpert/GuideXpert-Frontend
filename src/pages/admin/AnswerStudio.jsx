import { useRef, useState } from 'react';
import { FiAlertCircle, FiCheck, FiCopy, FiHelpCircle, FiLoader, FiMessageCircle, FiPenTool } from 'react-icons/fi';
import { useAuth } from '../../hooks/useAuth';
import { generateAnswerStudio } from '../../utils/adminApi';
import {
  ANSWER_STUDIO_PLATFORMS,
  ANSWER_STUDIO_QUESTION_LIMIT,
  beginGeneration,
  buildGeneratePayload,
  canAccessAnswerStudio,
  canGenerate,
  copyAnswerText,
  dismissGeneration,
  nextPlatform,
  normalizeStudioQuestion,
  questionValidation,
  settleGeneration,
} from '../../utils/answerStudio';

const PLATFORM_ICONS = {
  quora: FiHelpCircle,
  reddit: FiMessageCircle,
};

function fallbackCopy(value) {
  if (typeof document === 'undefined' || typeof document.execCommand !== 'function') return false;
  const area = document.createElement('textarea');
  area.value = value;
  area.setAttribute('readonly', '');
  area.style.position = 'fixed';
  area.style.left = '-9999px';
  document.body.appendChild(area);
  area.select();
  const copied = document.execCommand('copy');
  document.body.removeChild(area);
  return copied;
}

function formatWhen(value) {
  if (!value) return '';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '';
  return date.toLocaleString();
}

export default function AnswerStudio() {
  const { user } = useAuth();
  const [platform, setPlatform] = useState('quora');
  const [question, setQuestion] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [originalAnswer, setOriginalAnswer] = useState('');
  const [draftAnswer, setDraftAnswer] = useState('');
  const [editing, setEditing] = useState(false);
  const [metadata, setMetadata] = useState(null);
  const [copyMessage, setCopyMessage] = useState('');
  const [copyFailed, setCopyFailed] = useState(false);
  const requestId = useRef(0);

  const validation = questionValidation(question);
  const allowed = canAccessAnswerStudio(user);
  const edited = Boolean(originalAnswer) && draftAnswer !== originalAnswer;

  function applyPatch(patch) {
    if (!patch) return;
    if ('loading' in patch) setLoading(patch.loading);
    if ('error' in patch) setError(patch.error);
    if ('copyMessage' in patch) setCopyMessage(patch.copyMessage);
    if ('editing' in patch) setEditing(patch.editing);
    if ('originalAnswer' in patch) setOriginalAnswer(patch.originalAnswer);
    if ('draftAnswer' in patch) setDraftAnswer(patch.draftAnswer);
    if ('metadata' in patch) setMetadata(patch.metadata);
  }

  async function handleGenerate() {
    if (!canGenerate(question, loading)) return;
    const started = beginGeneration(requestId.current);
    requestId.current = started.requestId;
    applyPatch(started.patch);
    const result = await generateAnswerStudio(buildGeneratePayload(platform, question));
    applyPatch(settleGeneration(started.requestId, requestId.current, result));
  }

  function handleAnother() {
    if (loading) return;
    const dismissed = dismissGeneration(requestId.current, { question, platform });
    requestId.current = dismissed.requestId;
    applyPatch(dismissed.state);
    setCopyFailed(false);
  }

  function handlePlatformKeyDown(event) {
    const next = nextPlatform(platform, event.key);
    if (!next) return;
    event.preventDefault();
    setPlatform(next);
    document.getElementById(`answer-studio-platform-${next}`)?.focus();
  }

  async function handleCopy() {
    const result = await copyAnswerText(
      draftAnswer,
      typeof navigator === 'undefined' ? null : navigator.clipboard,
      fallbackCopy
    );
    setCopyFailed(!result.ok);
    setCopyMessage(result.message);
  }

  if (!allowed) {
    return (
      <section className="mx-auto max-w-3xl px-4 py-10 sm:px-6">
        <h1 className="text-2xl font-semibold text-slate-900">Answer Studio</h1>
        <p className="mt-3 rounded-xl border border-amber-200 bg-amber-50 px-4 py-3 text-sm text-amber-900" role="alert">
          You do not have access to Answer Studio. Ask a super admin to grant the Answer Studio section.
        </p>
      </section>
    );
  }

  return (
    <section className="mx-auto flex w-full max-w-5xl flex-col gap-6 px-4 py-6 sm:px-6 sm:py-8">
      <header className="flex flex-col gap-2">
        <div className="flex items-center gap-2 text-primary-navy">
          <FiPenTool className="h-5 w-5" aria-hidden="true" />
          <p className="text-xs font-semibold uppercase tracking-wide">Admin</p>
        </div>
        <h1 className="text-2xl font-semibold tracking-tight text-slate-900 sm:text-3xl">Answer Studio</h1>
        <p className="max-w-2xl text-sm leading-6 text-slate-600">
          Draft a Quora or Reddit answer from a question. Answers are generated by AI and need a human review before you copy them anywhere.
        </p>
        <p className="text-sm text-slate-500">Nothing is posted to Quora or Reddit from this page.</p>
      </header>

      <div
        className="grid gap-3 sm:grid-cols-2"
        role="radiogroup"
        aria-label="Platform"
        onKeyDown={handlePlatformKeyDown}
      >
        {ANSWER_STUDIO_PLATFORMS.map((item) => {
          const Icon = PLATFORM_ICONS[item.id];
          const selected = platform === item.id;
          return (
            <button
              key={item.id}
              id={`answer-studio-platform-${item.id}`}
              type="button"
              role="radio"
              aria-checked={selected}
              tabIndex={selected ? 0 : -1}
              onClick={() => setPlatform(item.id)}
              className={`rounded-2xl border px-4 py-4 text-left transition ${
                selected
                  ? 'border-primary-navy bg-primary-navy text-white shadow-sm'
                  : 'border-slate-200 bg-white text-slate-800 hover:border-slate-300'
              }`}
            >
              <span className="flex items-center gap-2 text-sm font-semibold">
                <Icon className="h-4 w-4" aria-hidden="true" />
                {item.name}
              </span>
              <span className={`mt-1 block text-sm leading-5 ${selected ? 'text-white/80' : 'text-slate-500'}`}>
                {item.description}
              </span>
            </button>
          );
        })}
      </div>

      <div className="rounded-2xl border border-slate-200 bg-white p-4 shadow-sm sm:p-5">
        <label htmlFor="answer-studio-question" className="text-sm font-semibold text-slate-900">
          Question
        </label>
        <textarea
          id="answer-studio-question"
          value={question}
          onChange={(event) => setQuestion(event.target.value)}
          rows={8}
          placeholder="Paste the Quora question or Reddit post."
          className="mt-2 w-full resize-y rounded-xl border border-slate-200 px-3 py-3 text-sm leading-6 text-slate-900 outline-none transition focus:border-primary-navy focus:ring-2 focus:ring-primary-navy/20"
        />
        <div className="mt-2 flex flex-wrap items-center justify-between gap-2 text-xs text-slate-500">
          <span>
            {normalizeStudioQuestion(question).length.toLocaleString()} / {ANSWER_STUDIO_QUESTION_LIMIT.toLocaleString()}
          </span>
          {!validation.ok && question.length > 0 ? (
            <span className="text-red-700" role="alert">{validation.message}</span>
          ) : null}
        </div>
        <div className="mt-4 flex flex-wrap items-center gap-3">
          <button
            type="button"
            onClick={handleGenerate}
            disabled={!canGenerate(question, loading)}
            className="inline-flex items-center gap-2 rounded-xl bg-primary-navy px-4 py-2.5 text-sm font-semibold text-white transition hover:bg-primary-navy/90 disabled:cursor-not-allowed disabled:bg-slate-300"
          >
            {loading ? <FiLoader className="h-4 w-4 animate-spin" aria-hidden="true" /> : null}
            {loading ? 'Generating…' : 'Generate answer'}
          </button>
          {loading ? (
            <p className="text-sm text-slate-600" role="status">Writing an answer. This can take a few seconds.</p>
          ) : null}
        </div>
        {error ? (
          <p className="mt-3 flex items-start gap-2 rounded-xl bg-red-50 px-3 py-2 text-sm text-red-800" role="alert">
            <FiAlertCircle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
            {error}
          </p>
        ) : null}
      </div>

      {metadata ? (
        <article className="rounded-2xl border border-slate-200 bg-white p-4 shadow-sm sm:p-5">
          <div className="flex flex-wrap items-start justify-between gap-3">
            <div>
              <h2 className="text-lg font-semibold text-slate-900">Generated answer</h2>
              <p className="mt-1 text-xs leading-5 text-slate-500">
                {metadata.platform} · {formatWhen(metadata.createdAt)}
                {metadata.model ? ` · ${metadata.model}` : ''}
                {metadata.promptKey ? ` · ${metadata.promptKey}` : ''}
                {metadata.promptSource ? ` · ${metadata.promptSource}` : ''}
              </p>
            </div>
            <div className="flex flex-wrap gap-2">
              <button
                type="button"
                onClick={() => setEditing((value) => !value)}
                className="rounded-lg border border-slate-200 px-3 py-2 text-sm font-medium text-slate-700 transition hover:bg-slate-50"
              >
                {editing ? 'Done editing' : 'Edit'}
              </button>
              <button
                type="button"
                onClick={handleCopy}
                className="inline-flex items-center gap-1.5 rounded-lg border border-slate-200 px-3 py-2 text-sm font-medium text-slate-700 transition hover:bg-slate-50"
              >
                {copyMessage && !copyFailed ? <FiCheck className="h-4 w-4" aria-hidden="true" /> : <FiCopy className="h-4 w-4" aria-hidden="true" />}
                Copy
              </button>
              <button
                type="button"
                onClick={handleAnother}
                disabled={loading}
                className="rounded-lg border border-slate-200 px-3 py-2 text-sm font-medium text-slate-700 transition hover:bg-slate-50 disabled:cursor-not-allowed disabled:opacity-50"
              >
                Generate another
              </button>
            </div>
          </div>
          <p className="mt-3 text-xs text-slate-500">
            {edited
              ? 'This edit is only in this browser. It is not saved to Answer Studio.'
              : 'Review the answer before you use it. Local edits are not saved.'}
          </p>
          {copyMessage ? (
            <p className={`mt-2 text-sm ${copyFailed ? 'text-red-700' : 'text-emerald-700'}`} role={copyFailed ? 'alert' : 'status'}>
              {copyMessage}
            </p>
          ) : null}
          {editing ? (
            <textarea
              aria-label="Edit answer"
              value={draftAnswer}
              onChange={(event) => setDraftAnswer(event.target.value)}
              rows={12}
              className="mt-4 w-full resize-y rounded-xl border border-slate-200 px-3 py-3 text-sm leading-6 text-slate-900 outline-none focus:border-primary-navy focus:ring-2 focus:ring-primary-navy/20"
            />
          ) : (
            <div className="mt-4 whitespace-pre-wrap text-sm leading-7 text-slate-800">{draftAnswer}</div>
          )}
        </article>
      ) : null}
    </section>
  );
}
